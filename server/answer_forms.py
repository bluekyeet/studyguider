"""Which kinds of answer input a question needs: text, a table, a drawing or a graph.

The rules come from the catalogue of real NCEA answer spaces (docs/design/answer-input-catalogue.md). A question generated by
the model records its own forms (normalise() checks them); an imported or older question has them inferred from its wording.
Every answer can still hold text, and the learner can add any other form themselves, so a wrong guess only changes what is
offered first.

A form is a small dict:
  {"kind": "text", "palette": "chemistry" | "maths" | "physics" | "general"}
  {"kind": "table", "columns": [...], "rows": [[...], ...]}     blank cells are the ones to fill; no columns = build your own
  {"kind": "drawing", "background": "blank" | "grid" | "figure", "purpose": "lewis" | "structure" | "diagram" | "label" | ""}
  {"kind": "graph", "x_label": "...", "y_label": "...", "x_range": [lo, hi] | None, "y_range": [lo, hi] | None}
"""
import re

KINDS = ("text", "table", "drawing", "graph")
PALETTES = ("chemistry", "maths", "physics", "general")
BACKGROUNDS = ("blank", "grid", "figure")
PURPOSES = ("lewis", "structure", "diagram", "label", "")

# The instruction words that ask for each form, from the catalogue's classification of 2,445 exam parts.
_TABLE = re.compile(r"complete the (?:following |two-way |frequency )?table|fill in the table|construct a (?:two-way )?table"
                    r"|complete the (?:following )?grid|in the table below,? (?:write|give|draw|complete)", re.I)
_LEWIS = re.compile(r"lewis (?:structure|diagram)|electron dot diagram", re.I)
_LEWIS_ASKED = re.compile(r"\bdraw\b|\bcomplete\b", re.I)
_STRUCTURE = re.compile(r"draw .{0,60}(?:structural formula|structures?\b|products?\b|isomers?|monomer|polymer|repeating unit|enantiomer"
                        r"|dipeptide|amino acid|zwitterion)|(?:give|write) the structural formulae?|(?:complete|devise|draw) (?:the |a )?"
                        r"(?:following )?reaction scheme|structural formulae? (?:of|for) (?:the |each )?(?:named |organic )?compounds?", re.I)
_GRAPH = re.compile(r"\bsketch\b|\bplot (?:the|a|your|these|points?|values)\b|draw .{0,40}(?:graph|curve|line of best fit|asymptote)|on the (?:axes|grid)(?: below| above| provided)?,?"
                    r" (?:sketch|draw|plot|mark|show)|(?:sketch|draw|plot|show) .{0,40}on the (?:axes|grid)|using the axes", re.I)
_ON_GIVEN_GRAPH = re.compile(r"\b(?:draw|sketch|add|mark|show|plot|label)\b.{0,50}(?:on|to) the graph\b(?! of)"
                             r"|add .{0,40}(?:line|curve) to the graph|draw lines on the graph", re.I)
_DIAGRAM = re.compile(r"draw .{0,40}(?:diagram|vectors?|arrows?|forces?|rays?|wavefronts?|pulses?|circuit|tree|phasor|field lines|path|"
                      r"resultant|nodes|antinodes|wave|harmonic|image)|ray diagram|free[- ]body|(?:add|complete) .{0,40}(?:the )?diagram"
                      r"|(?:draw|complete) (?:a |the )?(?:probability )?tree|in the box below,? draw|draw .{0,30}\bbox\b", re.I)
_LABEL = re.compile(r"\blabel (?:the|all|each)\b|\blabel .{0,30}on the (?:diagram|figure|graph)|clearly mark|mark .{0,40}on (?:the|your)|indicate on|include (?:force )?labels"
                    r"|with an asterisk|circle (?:one|the|an|all) .{0,40}(?:group|linkage|bond|atom|carbon)|on the diagram (?:above|below)", re.I)
_ON_FIGURE = re.compile(r"on the (?:diagram|figure|graph|picture)|to the (?:above |following )?diagram|(?:above|below) diagram"
                        r"|in (?:the )?figure|complete the ray diagram|on (?:diagram|figure) \w+", re.I)
_CHEMISTRY = re.compile(r"\\ce\{|equation for|half-equation|\bK[sac]\b|expression for k|\(aq\)|mol L", re.I)
_GRAPH_OF = re.compile(r"graph of (?:the )?([\w' ()/-]{1,40}?) (?:against|versus|vs\.?) (?:the )?([\w' ()/-]{1,30}?)(?=[ .,;:]|$)", re.I)
_FUNCTION = re.compile(r"(?:graph of|sketch) (?:the )?(?:gradient )?(?:function )?(?:y\s*=\s*)?([a-z]'?\(x\))", re.I)
_MARKDOWN_ROW = re.compile(r"^\s*\|.*\|\s*$")
_MARKDOWN_RULE = re.compile(r"^\s*\|?(?:\s*:?-{3,}:?\s*\|)+\s*:?-{0,}:?\s*\|?\s*$")


def palette_for(subject="", text=""):
    """Which symbol set the text box opens on."""
    name = (subject or "").lower()
    if "chem" in name or _CHEMISTRY.search(text or ""):
        return "chemistry"
    if "calc" in name or "math" in name or "statistic" in name:
        return "maths"
    if "physic" in name:
        return "physics"
    return "general"


def _cells(line):
    return [cell.strip() for cell in re.split(r"(?<!\\)\|", line.strip().strip("|"))]


def table_template(text):
    """The first Markdown table in the wording that has blank cells to fill, as columns and rows; None if there is none."""
    lines = (text or "").splitlines()
    i = 0
    while i < len(lines):
        if not _MARKDOWN_ROW.match(lines[i]):
            i += 1
            continue
        block = []
        while i < len(lines) and _MARKDOWN_ROW.match(lines[i]):
            block.append(lines[i])
            i += 1
        rows = [_cells(line) for line in block if not _MARKDOWN_RULE.match(line)]
        if len(rows) >= 2:
            header, body = rows[0], rows[1:]
            width = len(header)
            body = [(row + [""] * width)[:width] for row in body]
            if any(not cell for row in body for cell in row[1:]):
                return {"kind": "table", "columns": header[:12], "rows": [row[:12] for row in body[:30]]}
    return None


def _graph(text, subject):
    found = _GRAPH_OF.search(text)
    function = _FUNCTION.search(text)
    maths = palette_for(subject) == "maths"
    y_label = found.group(1).strip() if found else function.group(1) if function else ("y" if maths else "")
    x_label = found.group(2).strip() if found else ("x" if maths or function else "")
    return {"kind": "graph", "x_label": x_label[:40], "y_label": y_label[:40], "x_range": None, "y_range": None}


def infer(text, subject="", has_figure=False):
    """The forms one question (or one part of a question) asks for, from its wording. Always ends with text."""
    text = re.sub(r"[ \t]+", " ", text or "")
    flat = re.sub(r"\s+", " ", text)
    forms = []
    lewis = bool(_LEWIS.search(flat) and _LEWIS_ASKED.search(flat))     # "the Lewis structure of SF4 is shown" asks for none
    structure = bool(_STRUCTURE.search(flat))
    # Structures drawn into a table's cells are drawn on the canvas; their names go in the text.
    if not (lewis or structure):
        template = table_template(text)
        if template:
            forms.append(template)
        elif _TABLE.search(flat):
            forms.append({"kind": "table", "columns": [], "rows": []})
    if lewis:
        forms.append({"kind": "drawing", "background": "blank", "purpose": "lewis"})
    elif structure:
        forms.append({"kind": "drawing", "background": "blank", "purpose": "structure"})
    elif _ON_GIVEN_GRAPH.search(flat) and has_figure:
        forms.append({"kind": "drawing", "background": "figure", "purpose": "label"})
    elif _GRAPH.search(flat):
        forms.append({"kind": "drawing", "background": "figure", "purpose": "label"} if has_figure and _ON_GIVEN_GRAPH.search(flat)
                     else _graph(flat, subject))
    elif _DIAGRAM.search(flat) or _LABEL.search(flat):
        on_figure = has_figure and bool(_ON_FIGURE.search(flat) or _LABEL.search(flat))
        purpose = "label" if _LABEL.search(flat) and not _DIAGRAM.search(flat) else "diagram"
        forms.append({"kind": "drawing", "background": "figure" if on_figure else "blank", "purpose": purpose})
    forms.append({"kind": "text", "palette": palette_for(subject, flat)})
    return forms


def _text(value, limit):
    return value.strip()[:limit] if isinstance(value, str) else ""


def _range(value):
    if (isinstance(value, (list, tuple)) and len(value) == 2 and all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in value)
            and value[0] < value[1] and all(abs(v) < 1e9 for v in value)):
        return [value[0], value[1]]
    return None


def normalise(value, subject="", text=""):
    """A list of forms the model returned, checked and trimmed; None when there is nothing usable (the caller then infers)."""
    if isinstance(value, dict):
        value = [value]
    if not isinstance(value, list):
        return None
    forms = []
    for item in value[:4]:
        if isinstance(item, str):
            item = {"kind": item}
        if not isinstance(item, dict) or item.get("kind") not in KINDS or any(f["kind"] == item["kind"] for f in forms):
            continue
        kind = item["kind"]
        if kind == "text":
            # "general" is what a question stored without knowing its subject says; the subject decides then.
            palette = item.get("palette") if item.get("palette") in PALETTES and item.get("palette") != "general" else palette_for(subject, text)
            forms.append({"kind": "text", "palette": palette})
        elif kind == "table":
            columns = [_text(c, 80) for c in item.get("columns") or [] if isinstance(c, str)][:12]
            rows = [[_text(c, 200) if isinstance(c, str) else "" for c in row][:len(columns)] for row in item.get("rows") or []
                    if isinstance(row, list)][:30] if columns else []
            forms.append({"kind": "table", "columns": columns, "rows": [(row + [""] * len(columns))[:len(columns)] for row in rows]})
        elif kind == "drawing":
            forms.append({"kind": "drawing", "background": item.get("background") if item.get("background") in BACKGROUNDS else "blank",
                          "purpose": item.get("purpose") if item.get("purpose") in PURPOSES else ""})
        else:
            forms.append({"kind": "graph", "x_label": _text(item.get("x_label"), 40), "y_label": _text(item.get("y_label"), 40),
                          "x_range": _range(item.get("x_range")), "y_range": _range(item.get("y_range"))})
    if not forms:
        return None
    if not any(f["kind"] == "text" for f in forms):
        forms.append({"kind": "text", "palette": palette_for(subject, text)})
    return forms


def answerable(parts):
    """Labels of the parts that take an answer: a parent such as (b) only introduces (b)(i) and (b)(ii)."""
    labels = [str(p.get("label") or "") for p in parts if isinstance(p, dict)]
    return [label for label in labels if label and label != "context"
            and not any(other != label and other.startswith(label + "(") for other in labels)]


def _segment(question_text, label):
    """The lines of the question's full text that belong to one part. The paper parser keeps a printed table (such as a Lewis
    structure table) out of the part's own wording, but its words are still in the question text between the part labels."""
    lines = (question_text or "").splitlines()
    tokens = re.findall(r"[a-h]|[ivx]+", label.replace("(", " ").replace(")", " "))
    start = 0
    for token in tokens:
        start = next((i + 1 for i in range(start, len(lines)) if re.match(rf"^\s*\({token}\)", lines[i])), None)
        if start is None:
            return ""
    end = next((i for i in range(start, len(lines)) if re.match(r"^\s*\([a-hivx]+\)", lines[i])), len(lines))
    return "\n".join(lines[start - 1:end])


def for_question(question_text, subject="", parts=None, stored=None):
    """Forms for a whole question: {"": forms} for the question itself plus {label: forms} for each answerable part.
    Stored forms (recorded when the question was made) win; anything missing is inferred."""
    stored = stored if isinstance(stored, dict) else {"": stored} if isinstance(stored, list) else {}
    parts = [p for p in (parts or []) if isinstance(p, dict)]
    result = {"": normalise(stored.get(""), subject, question_text)
              or infer(question_text, subject, any(p.get("diagrams") for p in parts))}
    by_label = {str(p.get("label") or ""): p for p in parts}
    for label in answerable(parts):
        part = by_label[label]
        wording = part.get("text", "")
        segment = _segment(question_text, label)
        if len(segment) > len(wording):
            wording = segment
        result[label] = normalise(stored.get(label), subject, wording) or infer(wording, subject, bool(part.get("diagrams")))
    return result


def merged(by_label):
    """One list for an answer given in a single box (rapid questions): each kind once, the first one asked for, text last."""
    forms = []
    for label_forms in by_label.values():
        for form in label_forms or []:
            if form["kind"] != "text" and not any(f["kind"] == form["kind"] for f in forms):
                forms.append(form)
    text = next((f for fs in by_label.values() for f in fs or [] if f["kind"] == "text"), {"kind": "text", "palette": "general"})
    return forms[:3] + [text]


# For prompts that generate questions: one sentence the model can follow, and the JSON shape it returns.
PROMPT = ("Also give answer_forms: a list saying what the learner must produce, using only these kinds: "
          "{\"kind\": \"text\"} for written or worked answers (always include it), "
          "{\"kind\": \"table\", \"columns\": [headers], \"rows\": [[cells, empty string for each cell to fill]]} for a table to complete, "
          "{\"kind\": \"drawing\", \"background\": \"blank\" or \"grid\", \"purpose\": \"lewis\", \"structure\" or \"diagram\"} for a Lewis "
          "structure, structural formula, reaction scheme or diagram to draw, and "
          "{\"kind\": \"graph\", \"x_label\": ..., \"y_label\": ..., \"x_range\": [lo, hi] or null, \"y_range\": [lo, hi] or null} for a "
          "graph to sketch or plot. Most questions need only [{\"kind\": \"text\"}].")
